package report

import (
	"fmt"
	"strings"
)

// ToMarkdown renders the full assessment report.
func ToMarkdown(r *Report) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# RedOps Assessment Report — %s\n\n", r.Project.Name)
	fmt.Fprintf(&b, "Generated: %s\n\n", fmtTime(r.Generated))
	if r.Project.Description != "" {
		fmt.Fprintf(&b, "> %s\n\n", r.Project.Description)
	}

	b.WriteString("## Executive summary\n\n")
	m := r.Metrics
	fmt.Fprintf(&b, "| Metric | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| Hosts discovered | %d |\n", m.Hosts)
	fmt.Fprintf(&b, "| Services discovered | %d |\n", m.Services)
	fmt.Fprintf(&b, "| Findings | %d (critical %d, high %d, validated %d) |\n", m.Findings, m.Critical, m.High, m.Validated)
	fmt.Fprintf(&b, "| ATT&CK techniques observed | %d / %d |\n", m.Techniques, m.TechniquesTot)
	fmt.Fprintf(&b, "| Attack paths | %d |\n", m.Paths)
	fmt.Fprintf(&b, "| Evidence records | %d (chain %s) |\n\n", m.Evidence, chainWord(m.EvidenceOK))

	b.WriteString("## Scope\n\n")
	if len(r.Scopes) == 0 {
		b.WriteString("No scope entries.\n\n")
	} else {
		for _, s := range r.Scopes {
			fmt.Fprintf(&b, "- `%s` (%s)\n", s.Value, s.Type)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Targets\n\n")
	if len(r.Targets) == 0 {
		b.WriteString("No targets.\n\n")
	} else {
		for _, t := range r.Targets {
			fmt.Fprintf(&b, "- `%s`\n", t.Value)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Assets\n\n")
	if len(r.Services) == 0 {
		b.WriteString("No services discovered.\n\n")
	} else {
		b.WriteString("| Host | Port | Service | Product |\n|---|---|---|---|\n")
		for _, s := range r.Services {
			prod := strings.TrimSpace(s.Product + " " + s.Version)
			fmt.Fprintf(&b, "| %s | %d/%s | %s | %s |\n", s.HostIP, s.Port, s.Protocol, orDash(s.Name), orDash(prod))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Findings\n\n")
	if len(r.Findings) == 0 {
		b.WriteString("No findings.\n\n")
	} else {
		for _, f := range r.Findings {
			fmt.Fprintf(&b, "### [%s] %s\n\n", strings.ToUpper(f.Severity), f.Title)
			fmt.Fprintf(&b, "- Target: `%s`\n- Confidence: %s · Status: %s\n", f.Target, f.Confidence, f.Status)
			if f.CWE != "" || f.TechniqueID != "" {
				fmt.Fprintf(&b, "- %s %s\n", cweWord(f.CWE), techWord(f.TechniqueID))
			}
			if f.Description != "" {
				fmt.Fprintf(&b, "- %s\n", f.Description)
			}
			if f.Evidence != "" {
				fmt.Fprintf(&b, "- Evidence: %s\n", f.Evidence)
			}
			if f.Remediation != "" {
				fmt.Fprintf(&b, "- Remediation: %s\n", f.Remediation)
			}
			b.WriteString("\n")
		}
	}

	b.WriteString("## MITRE ATT&CK coverage\n\n")
	fmt.Fprintf(&b, "Observed %d of %d techniques.\n\n", m.Techniques, m.TechniquesTot)
	for _, tac := range r.Coverage.Tactics {
		if tac.Seen == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s (%d/%d)\n\n", tac.Tactic, tac.Seen, tac.Total)
		for _, h := range tac.Techniques {
			fmt.Fprintf(&b, "- %s %s (×%d, %s)\n", h.ID, h.Name, h.Count, strings.Join(h.Sources, ","))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Attack paths\n\n")
	if len(r.Paths) == 0 {
		b.WriteString("No attack paths generated. Run `paths generate` after discovery.\n\n")
	} else {
		for i, p := range r.Paths {
			fmt.Fprintf(&b, "### Path %d — risk %d (%s)\n\n", i+1, p.Risk, p.Confidence)
			fmt.Fprintf(&b, "Objective: %s\n\n", orDash(p.Objective))
			if p.Techniques != "" {
				fmt.Fprintf(&b, "Techniques: %s\n\n", p.Techniques)
			}
		}
	}

	b.WriteString("## Timeline\n\n")
	if len(r.Timeline) == 0 {
		b.WriteString("No events.\n\n")
	} else {
		for _, e := range r.Timeline {
			fmt.Fprintf(&b, "- %s [%s] %s\n", e.Timestamp.UTC().Format("15:04:05"), e.Kind, e.Message)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Evidence integrity\n\n")
	fmt.Fprintf(&b, "Chain verification: **%s** over %d records.\n\n", chainWord(m.EvidenceOK), m.Evidence)

	b.WriteString("---\n\n*Generated by RedOps. Covers authorized assessment activity only; findings are point-in-time observations.*\n")
	return b.String()
}

func chainWord(ok bool) string {
	if ok {
		return "OK"
	}
	return "BROKEN"
}

func cweWord(cwe string) string {
	if cwe == "" {
		return ""
	}
	return cwe
}

func techWord(t string) string {
	if t == "" {
		return ""
	}
	return t
}
